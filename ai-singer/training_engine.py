@dataclass(frozen=True)
class TrainingConfig:
    learning_rate: float = 2e-4
    weight_decay: float = 1e-4
    gradient_clip_norm: float = 1.0
    mel_loss_weight: float = 1.0
    f0_loss_weight: float = 0.25
    voicing_loss_weight: float = 0.1
    energy_loss_weight: float = 0.1
    seed: int = 2026

    def validate(self) -> "TrainingConfig":
        for name in ("learning_rate", "gradient_clip_norm", "mel_loss_weight",
                     "f0_loss_weight", "voicing_loss_weight", "energy_loss_weight"):
            value = getattr(self, name)
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f"{name} must be finite and positive")
        if not math.isfinite(self.weight_decay) or self.weight_decay < 0:
            raise ValueError("weight_decay must be finite and non-negative")
        if isinstance(self.seed, bool) or not isinstance(self.seed, int):
            raise ValueError("seed must be an integer")
        return self


def _torch():
    try:
        import torch
        from torch.nn import functional as F
    except ImportError as exc:
        raise RuntimeError("Install ai-singer/training-requirements.txt to use training") from exc
    return torch, F


def _batch_tensors(batch: TrainingBatch, device):
    torch, _ = _torch()
    def tensor(value, dtype):
        return torch.as_tensor(np.asarray(value), dtype=dtype, device=device)
    return {
        "phoneme_ids": tensor(batch.phoneme_ids, torch.long),
        "note_ids": tensor(batch.note_ids, torch.long),
        "conditioning_f0_hz": tensor(batch.conditioning_f0_hz, torch.float32),
        "conditioning_voicing_mask": tensor(batch.conditioning_voicing_mask, torch.float32),
        "conditioning_energy": tensor(batch.conditioning_energy, torch.float32),
        "valid_frame_mask": tensor(batch.valid_frame_mask, torch.bool),
        "target_log_mel": tensor(batch.target_log_mel, torch.float32),
        "target_f0_hz": tensor(batch.target_f0_hz, torch.float32),
        "target_voicing_mask": tensor(batch.target_voicing_mask, torch.float32),
        "target_log_rms": tensor(batch.target_log_rms, torch.float32),
    }


def _masked_mean(values, mask):
    torch, _ = _torch()
    weights = mask.to(values.dtype)
    denominator = weights.sum()
    if denominator.item() <= 0:
        raise ValueError("loss mask must contain at least one valid frame")
    while weights.ndim < values.ndim:
        weights = weights.unsqueeze(-1)
    weights = weights.expand_as(values)
    return (values * weights).sum() / weights.sum().clamp_min(1.0)


def compute_training_loss(outputs, batch: TrainingBatch, weights: TrainingConfig):
    """Return total and named masked losses, excluding padded frames."""
    torch, F = _torch()
    target = _batch_tensors(batch, outputs["log_mel"].device)
    mask = target["valid_frame_mask"]
    mel = _masked_mean((outputs["log_mel"] - target["target_log_mel"]).square(), mask)
    # Log-F0 stabilizes the scale across low and high notes; unvoiced frames
    # are excluded from the F0 regression term.
    voiced = mask & (target["target_voicing_mask"] > 0.5)
    if voiced.any():
        f0 = _masked_mean(
            (torch.log1p(outputs["f0_hz"]) - torch.log1p(target["target_f0_hz"])).square(),
            voiced,
        )
    else:
        f0 = outputs["f0_hz"].sum() * 0.0
    voice = _masked_mean(
        F.binary_cross_entropy_with_logits(
            outputs["voicing_logits"], target["target_voicing_mask"], reduction="none"
        ),
        mask,
    )
    energy = _masked_mean(
        (outputs["log_rms"] - target["target_log_rms"]).square(), mask
    )
    total = (
        weights.mel_loss_weight * mel
        + weights.f0_loss_weight * f0
        + weights.voicing_loss_weight * voice
        + weights.energy_loss_weight * energy
    )
    return total, {
        "mel": mel,
        "f0": f0,
        "voicing": voice,
        "energy": energy,
    }


def _forward(model, tensors):
    return model(
        tensors["phoneme_ids"],
        tensors["note_ids"],
        tensors["conditioning_f0_hz"],
        tensors["conditioning_voicing_mask"],
        tensors["conditioning_energy"],
        tensors["valid_frame_mask"],
    )


def train_one_epoch(model, batches: Iterable[TrainingBatch], optimizer, config: TrainingConfig, *, device="cpu"):
    torch, _ = _torch()
    config.validate()
    model.train()
    totals = {"loss": 0.0, "mel": 0.0, "f0": 0.0, "voicing": 0.0, "energy": 0.0}
    count = 0
    for batch in batches:
        tensors = _batch_tensors(batch, device)
        optimizer.zero_grad(set_to_none=True)
        outputs = _forward(model, tensors)
        loss, parts = compute_training_loss(outputs, batch, config)
        if not torch.isfinite(loss):
            raise FloatingPointError("non-finite training loss")
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), config.gradient_clip_norm)
        optimizer.step()
        totals["loss"] += float(loss.detach().cpu())
        for key, value in parts.items():
            totals[key] += float(value.detach().cpu())
        count += 1
    if count == 0:
        raise ValueError("training requires at least one batch")
    return {key: value / count for key, value in totals.items()} | {"batches": count}


